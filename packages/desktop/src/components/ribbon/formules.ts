/**
 * Formulebibliotheek: standaardformules uit de mechanica en de Eurocodes, als
 * fragment in de rekentaal om met één klik in een rekenblad te zetten.
 *
 * Elk fragment rekent zelfstandig door: eerst de invoer met een realistische
 * voorbeeldwaarde en eenheid, dan de formule(s) met de naam van de uitkomst in
 * de notatie van de norm (een komma in een index zoals in de bladen: `f_m,d`,
 * `M_c,Rd`). Achter een normformule staat als toelichting het nummer van de
 * vergelijking, bijvoorbeeld `', (6.13)'`; de volledige verwijzing staat in
 * `bron`.
 *
 * Een paar fragmenten gebruiken de projectgegevens die elk blad vóór de eerste
 * regel in de scope krijgt (`CC`, `K_FI`, zie store/projectGegevens.ts); die
 * namen staan in `projectvariabelen`.
 *
 * Bewust nooit een variabele met de naam van een eenheid (`s`, `m`, `N`, `K`,
 * `g`, …): die overschaduwt de eenheid in alle volgende regels van het blad,
 * zonder foutmelding (`27 m/s` wordt dan iets anders). Daarom heet de
 * sneeuwbelasting `s_1`, de beugelafstand `s_l` en een massa `m_l` of `m_A`.
 *
 * Gecontroleerd door scripts/check-formules.mjs: elk fragment rekent zonder
 * foutmelding door en een selectie uitkomsten klopt met een handberekening.
 *
 * De voorbeelden van de Library staan hier niet: die komen bij het opstarten uit de
 * map library/ van de repository (store/library.ts, docs/library.md). Ze hebben
 * tekstregels, dus twee talen: `code` en `codeEn`.
 */

export interface Tekst {
  nl: string;
  en: string;
}

export interface FormuleGroep {
  /** Groep-id, bijv. "mechanica-ligger" of "en1995". */
  id: string;
  naam: Tekst;
}

/** Een groep van de Library in het projectpaneel. */
export interface LibraryGroep {
  id: string;
  naam: Tekst;
  /** Wat erin zit, kort: naast de naam in het paneel. */
  onder: Tekst;
}

export interface Formule {
  /** Uniek, kebab-case. */
  id: string;
  /** Id uit FORMULE_GROEPEN. */
  groep: string;
  /** Korte naam. */
  naam: Tekst;
  /** Herkomst, bijv. "NEN-EN 1995-1-1 6.1.6 (6.11)" of "mechanica". */
  bron?: string;
  /** Eén zin uitleg. */
  uitleg?: Tekst;
  /** Het in te voegen fragment in de rekentaal; meerdere regels. */
  code: string;
  /** Hetzelfde fragment met Engelse tekst, als het tekstregels heeft; zie codeVan. */
  codeEn?: string;
  /**
   * Projectvariabelen die het fragment gebruikt zonder ze zelf te zetten
   * (`CC`, `K_FI`). In de app staan die altijd in de scope.
   */
  projectvariabelen?: string[];
  /** Staat in deze groep van de Library. */
  library?: string;
  /** Het voorbeeld tekent ook iets; bepaalt het icoon in de Library. */
  soort?: "grafiek" | "tekening";
  /** Welk plaatje erbij hoort (formuleBeeld.ts), als dat niet het plaatje van `id` is. */
  beeld?: string;
}

/** Regels van een fragment, onder elkaar. */
const c = (...regels: string[]): string => regels.join("\n");

/** Het fragment in de taal van de app; zonder tekstregels is er maar één. */
export const codeVan = (f: Formule, taal: string | undefined): string =>
  (taal?.startsWith("en") ? f.codeEn : undefined) ?? f.code;

